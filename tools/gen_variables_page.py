"""Write docs/reference/variables.md from the packaged registry (run after rebuilding the registry)."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
reg = json.loads((ROOT / "vitaldb_resolution" / "data" / "registry.json").read_text(encoding="utf-8"))


def cell(x):
    return str(x).replace("|", "\\|").replace("\n", " ") if x not in (None, "") else ""


lines = ["# Variables", "",
         f"All {len(reg['variables'])} entries of the packaged registry (schema {reg['schema_version']}, built "
         f"{reg['built']}). Generated by `tools/gen_variables_page.py`; the full entry, with rules and "
         "covariates, is `Registry.entry(name)`.", ""]
for source in ("clinical", "lab"):
    rows = [e for e in reg["variables"].values() if e.get("source") == source]
    lines += [f"## {source.capitalize()} ({len(rows)})", "",
              "| Variable | Description | Unit | Method | Resolution | Anchor | Evidence |",
              "|---|---|---|---|---|---|---|"]
    for e in rows:
        lines.append("| `{}` | {} | {} | `{}` | {} | {} | {} |".format(
            e["variable"], cell(e.get("description")), cell(e.get("unit")), e.get("method", ""),
            cell(e.get("resolution")), cell(e.get("anchor")), cell(e.get("evidence"))))
    lines.append("")
other = [e for e in reg["variables"].values() if e.get("source") not in ("clinical", "lab")]
if other:
    lines += ["## Derived and other", "", "| Variable | Description | Unit | Method |", "|---|---|---|---|"]
    lines += [f"| `{e['variable']}` | {cell(e.get('description'))} | {cell(e.get('unit'))} | `{e.get('method', '')}` |"
              for e in other]
(ROOT / "docs" / "reference" / "variables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", len(reg["variables"]), "variables")
